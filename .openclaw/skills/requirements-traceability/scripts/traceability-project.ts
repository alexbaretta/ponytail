export interface TraceabilitySourceScopeV5 {
 readonly kind: 'implementation' | 'unit-test' | 'integration-test';
 readonly include: readonly string[];
 readonly locator: 'text' | 'typescript';
}
export interface TraceabilityExclusionV5 { readonly pattern: string; readonly reason: string }
export interface TraceabilityGeneratedArtifactV5 { readonly path: string; readonly sourcePath: string }
export interface TraceabilityTypescriptV5 { readonly cliPath: string; readonly projectPath: string }
export interface TraceabilityConfigurationV5 {
 readonly schemaVersion: 5;
 readonly projectRoot: string;
 readonly requirementsRoot: string;
 readonly uatRoot: string;
 readonly sources: readonly TraceabilitySourceScopeV5[];
 readonly exclusions: readonly TraceabilityExclusionV5[];
 readonly generatedArtifacts: readonly TraceabilityGeneratedArtifactV5[];
 readonly reverseViewPath: string;
 readonly typescript: TraceabilityTypescriptV5 | null;
}
export interface TraceabilityProjectFinding {
 readonly code: 'empty-scope' | 'unclassified-source' | 'ambiguous-source' | 'unclassified-generated-source' | 'generated-marker' | 'misplaced-declaration';
 readonly path: string;
 readonly line: number;
 readonly message: string;
}
export interface TraceabilityProject {
 readonly graph: TraceabilityGraph;
 readonly discoveryFindings: readonly TraceabilityDiscoveryFinding[];
 readonly graphFindings: readonly TraceabilityGraphFinding[];
 readonly projectFindings: readonly TraceabilityProjectFinding[];
 readonly sources: readonly TraceabilitySource[];
}

export const traceabilityGeneratedHeader = '<!-- Generated by requirements-traceability V5. Do not edit. -->';

export function traceabilityReverseViewPath(root: string, relative: string): string {
 let current = root;
 for (const component of relative.split('/')) {
  current = path.join(current,component);
  if (fs.lstatSync(current,{throwIfNoEntry:false})?.isSymbolicLink()) throw new Error('Traceability reverse view must not traverse symbolic links');
 }
 if (fs.existsSync(current)) {
  const text = fs.readFileSync(current,'utf8');
  if (!text.startsWith(`${traceabilityGeneratedHeader}\n`) && !text.startsWith('<!-- Generated by requirements-traceability. Do not edit. -->\n')) {
   throw new Error(`Refusing to replace authored reverse-view path: ${relative}`);
  }
 }
 return current;
}

function isRecord(value: unknown): value is Record<string, unknown> {
 return typeof value === 'object' && value !== null && !Array.isArray(value);
}
function object(value: unknown, keys: readonly string[], label: string): Record<string, unknown> {
 if (!isRecord(value) || Object.keys(value).some(key => !keys.includes(key)) || keys.some(key => !(key in value))) {
  throw new Error(`${label} must contain exactly: ${keys.join(', ')}`);
 }
 return value;
}
function string(value: unknown, label: string): string {
 if (typeof value !== 'string' || value.trim() !== value || !value) throw new Error(`${label} must be a non-empty trimmed string`);
 return value;
}
function array(value: unknown, label: string): readonly unknown[] {
 if (!Array.isArray(value)) throw new Error(`${label} must be an array`);
 return value;
}
function relative(value: unknown, label: string, glob = false): string {
 const result = string(value, label);
 if (path.posix.isAbsolute(result) || path.win32.isAbsolute(result) || result.includes('\\') || result.includes('\0')
  || result.split('/').some(part => !part || part === '.' || part === '..')
  || (!glob && /[?*{}[\]]/u.test(result))) throw new Error(`${label} must be a canonical project-relative ${glob ? 'glob' : 'path'}`);
 return result;
}

// Traceability: implements OBL-CM-GRAPH from implementation readTraceabilityConfigurationV5
export function readTraceabilityConfigurationV5(document: unknown): TraceabilityConfigurationV5 {
 const record = object(document, ['schemaVersion','projectRoot','requirementsRoot','uatRoot','sources','exclusions','generatedArtifacts','reverseViewPath','typescript'], 'V5 configuration');
 if (record.schemaVersion !== 5) throw new Error('V5 configuration schemaVersion must be 5');
 const projectRoot = string(record.projectRoot, 'projectRoot');
 if (path.posix.isAbsolute(projectRoot) || path.win32.isAbsolute(projectRoot) || projectRoot.includes('\0') || projectRoot.includes('\\')) throw new Error('projectRoot must be relative to the configuration file');
 const requirementsRoot = relative(record.requirementsRoot, 'requirementsRoot');
 const uatRoot = relative(record.uatRoot, 'uatRoot');
 if (within(requirementsRoot, uatRoot) || within(uatRoot, requirementsRoot)) throw new Error('Requirement and UAT scopes must be disjoint');
 const sources = array(record.sources, 'sources').map((value): TraceabilitySourceScopeV5 => {
  const scope = object(value, ['kind','include','locator'], 'source scope');
  if (scope.kind !== 'implementation' && scope.kind !== 'unit-test' && scope.kind !== 'integration-test') throw new Error('Unsupported source kind');
  if (scope.locator !== 'text' && scope.locator !== 'typescript') throw new Error('Unsupported source locator');
  const include = array(scope.include, 'include').map(value => relative(value, 'include pattern', true));
  if (!include.length || new Set(include).size !== include.length) throw new Error('Source include patterns must be nonempty and unique');
  return {kind:scope.kind, include, locator:scope.locator};
 });
 const exclusions = array(record.exclusions, 'exclusions').map((value): TraceabilityExclusionV5 => {
  const exclusion = object(value, ['pattern','reason'], 'exclusion');
  return {pattern:relative(exclusion.pattern, 'exclusion pattern', true), reason:string(exclusion.reason, 'exclusion reason')};
 });
 const generatedArtifacts = array(record.generatedArtifacts, 'generatedArtifacts').map((value): TraceabilityGeneratedArtifactV5 => {
  const generatedArtifact = object(value, ['path','sourcePath'], 'generated artifact');
  return {path:relative(generatedArtifact.path,'generated path'), sourcePath:relative(generatedArtifact.sourcePath,'canonical source path')};
 });
 if (new Set(generatedArtifacts.map(item => item.path)).size !== generatedArtifacts.length) throw new Error('Duplicate generated path');
 for (const item of generatedArtifacts) {
  if (within(requirementsRoot,item.path) || within(uatRoot,item.path)) throw new Error('Generated mappings cannot omit requirement or UAT declarations');
  if (generatedArtifacts.some(candidate => candidate.path === item.sourcePath)) throw new Error('Generated mappings must point directly to canonical source');
 }
 let typescript: TraceabilityTypescriptV5 | null = null;
 if (record.typescript !== null) {
  const configuredTypescript = object(record.typescript, ['cliPath','projectPath'], 'typescript');
  typescript = {cliPath:relative(configuredTypescript.cliPath,'typescript.cliPath'), projectPath:relative(configuredTypescript.projectPath,'typescript.projectPath')};
 }
 if (sources.some(scope => scope.locator === 'typescript') && typescript === null) throw new Error('TypeScript sources require the semantic checker configuration');
 return {schemaVersion:5, projectRoot, requirementsRoot, uatRoot, sources, exclusions, generatedArtifacts,
  reverseViewPath:relative(record.reverseViewPath,'reverseViewPath'), typescript};
}

function within(directory: string, file: string): boolean { return file === directory || file.startsWith(`${directory}/`); }

function withoutSymlinks(root: string, file: string): string {
 const absolute = path.join(root, file);
 let current = root;
 for (const component of file.split('/')) {
  current = path.join(current, component);
  if (fs.lstatSync(current).isSymbolicLink()) throw new Error(`Traceability source must not traverse a symbolic link: ${file}`);
 }
 return absolute;
}

function regularFile(root: string, file: string): string {
 const absolute = withoutSymlinks(root,file);
 if (!fs.statSync(absolute).isFile()) throw new Error(`Traceability source must be a regular file: ${file}`);
 return absolute;
}

function markdownFiles(root: string, directory: string): readonly string[] {
 if (!fs.lstatSync(path.join(root,directory),{throwIfNoEntry:false})) return [];
 const absolute = withoutSymlinks(root,directory);
 if (!fs.statSync(absolute).isDirectory()) throw new Error(`PM scope must be a directory: ${directory}`);
 const files: string[] = [];
 for (const entry of fs.readdirSync(absolute,{withFileTypes:true})) {
  const file = `${directory}/${entry.name}`;
  if (entry.isSymbolicLink()) throw new Error(`Traceability PM scope must not contain a symbolic link: ${file}`);
  if (entry.isDirectory()) files.push(...markdownFiles(root,file));
  else if (entry.name.endsWith('.md')) files.push(file);
 }
 return files;
}

// Traceability: implements OBL-CM-GRAPH from implementation discoverTraceabilityProject
// Traceability: implements OBL-CM-ACCEPTANCE-COVERAGE from implementation discoverTraceabilityProject
export function discoverTraceabilityProject(traceabilityConfigurationV5: TraceabilityConfigurationV5, configurationPath: string, invokingRoot: string): TraceabilityProject {
 const root = fs.realpathSync(invokingRoot);
 const configuredRoot = fs.realpathSync(path.resolve(path.dirname(configurationPath), traceabilityConfigurationV5.projectRoot));
 if (root !== configuredRoot) throw new Error('Traceability configuration projectRoot does not match the invoking repository');
 traceabilityReverseViewPath(root,traceabilityConfigurationV5.reverseViewPath);
 const gitRoot = execFileSync('git', ['rev-parse','--show-toplevel'], {cwd:root,encoding:'utf8'}).trim();
 if (fs.realpathSync(gitRoot) !== root) throw new Error('Invoking root must be the repository root');
 const gitFiles = execFileSync('git', ['ls-files','--cached','--others','--exclude-standard','-z'], {cwd:root,encoding:'utf8',maxBuffer:64*1024*1024}).split('\0').filter(Boolean);
 // PM declarations are authoritative even before admission to Git; ignore rules cannot hide an acceptance.
 const files = [...new Set([...gitFiles,...markdownFiles(root,traceabilityConfigurationV5.requirementsRoot),...markdownFiles(root,traceabilityConfigurationV5.uatRoot)])].sort();
 const sources: TraceabilitySource[] = [];
 const entities: TraceabilityGraphEntity[] = [];
 const relationships: TraceabilityGraphRelationship[] = [];
 const discoveryFindings: TraceabilityDiscoveryFinding[] = [];
 const projectFindings: TraceabilityProjectFinding[] = [];
 const generated = new Map(traceabilityConfigurationV5.generatedArtifacts.map(item => [item.path,item.sourcePath]));
 for (const file of files) {
  if (file === traceabilityConfigurationV5.reverseViewPath) continue;
  // An unstaged deletion remains in the Git index; a dangling link is not a deletion.
  const stat = fs.lstatSync(path.join(root,file),{throwIfNoEntry:false});
  if (!stat) continue;
  const requirement = within(traceabilityConfigurationV5.requirementsRoot,file);
  const acceptance = within(traceabilityConfigurationV5.uatRoot,file);
  if (generated.has(file)) continue;
  const scopes = traceabilityConfigurationV5.sources.filter(scope => scope.include.some(pattern => path.posix.matchesGlob(file,pattern)));
  if (!requirement && !acceptance && traceabilityConfigurationV5.exclusions.some(item => path.posix.matchesGlob(file,item.pattern))) continue;
  let kind: TraceabilitySource['kind'];
  if (requirement || acceptance) {
   if (stat.isSymbolicLink()) throw new Error(`Traceability PM scope must not contain a symbolic link: ${file}`);
   if (!file.endsWith('.md')) continue;
   kind = 'markdown';
  } else {
   if (!scopes.length) {
    if (stat.isFile() && /\.(?:[cm]?[jt]s|[jt]sx)$/u.test(file)) {
     const text = fs.readFileSync(regularFile(root,file),'utf8');
     if (!/Traceability\s*:/iu.test(text)) continue;
     const typescript: typeof ts = createRequire(path.join(root,'package.json'))('typescript');
     const sourceFile = typescript.createSourceFile(file,text,typescript.ScriptTarget.Latest,true);
     const positions = new Set<number>();
     const visit = (node: ts.Node): void => {
      for (const commentRange of typescript.getLeadingCommentRanges(text,node.pos) ?? []) {
       if (positions.has(commentRange.pos)) continue;
       positions.add(commentRange.pos);
       const discovery = discoverTraceabilitySource({kind:'implementation',path:file,text:text.slice(commentRange.pos,commentRange.end)});
       if (discovery.graph.entities.length || discovery.findings.some(finding => finding.code === 'unexpected-kind')) {
        projectFindings.push({code:'unclassified-source',path:file,line:sourceFile.getLineAndCharacterOfPosition(commentRange.pos).line+1,
         message:'Annotated source requires an explicit source classification or exclusion'});
       }
      }
      typescript.forEachChild(node,visit);
     };
     visit(sourceFile);
    }
    continue;
   }
   if (scopes.length !== 1) {
    projectFindings.push({code:'ambiguous-source',path:file,line:1,message:'Source matches more than one classification'});
    continue;
   }
   const scope = scopes[0];
   if (!scope) throw new Error('Missing selected source scope');
   kind = scope.kind;
  }
  const traceabilitySource: TraceabilitySource = {kind,path:file,text:fs.readFileSync(regularFile(root,file),'utf8')};
  sources.push(traceabilitySource);
  const discovery = discoverTraceabilitySource(traceabilitySource);
  for (const entity of discovery.graph.entities) {
   if ((requirement && entity.kind === 'acceptance') || (acceptance && entity.kind !== 'acceptance')) {
    projectFindings.push({code:'misplaced-declaration',path:file,line:entity.line,message:`${entity.kind} ${entity.id} is outside its canonical PM scope`});
   }
  }
  entities.push(...discovery.graph.entities);
  relationships.push(...discovery.graph.relationships);
  discoveryFindings.push(...discovery.findings);
 }
 for (const item of traceabilityConfigurationV5.generatedArtifacts) {
  if (!sources.some(source => source.path === item.sourcePath && source.kind !== 'markdown')) {
   projectFindings.push({code:'unclassified-generated-source',path:item.path,line:1,message:`Canonical source ${item.sourcePath} is not a discovered executable source`});
  }
  if (fs.lstatSync(path.join(root,item.path),{throwIfNoEntry:false})) {
   const text = fs.readFileSync(regularFile(root,item.path),'utf8');
   if (/Traceability\s*:/iu.test(text)) projectFindings.push({code:'generated-marker',path:item.path,line:1,message:'Generated output must not duplicate canonical source annotations'});
  }
 }
 for (const kind of ['requirement','acceptance']) {
  if (!entities.some(entity => entity.kind === kind)) projectFindings.push({code:'empty-scope',path:kind === 'requirement' ? traceabilityConfigurationV5.requirementsRoot : traceabilityConfigurationV5.uatRoot,line:1,message:`No ${kind} declarations discovered`});
 }
 const graph: TraceabilityGraph = {entities,relationships};
 return {graph,discoveryFindings,graphFindings:validateTraceabilityGraph(graph),projectFindings,sources};
}
